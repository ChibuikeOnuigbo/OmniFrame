import assert from 'node:assert/strict'
import os from 'node:os'
import path from 'node:path'
import {chromium} from 'playwright'
import chrome,{inflate} from '@sparticuz/chromium'
await inflate(path.resolve('node_modules/@sparticuz/chromium/bin/al2023.tar.br'))
process.env.LD_LIBRARY_PATH=`${os.tmpdir()}/al2023/lib:${os.tmpdir()}:${process.env.LD_LIBRARY_PATH||''}`
const browser=await chromium.launch({executablePath:await chrome.executablePath(),args:['--no-sandbox']})
try{
 const page=await browser.newPage({viewport:{width:1280,height:850}})
 page.setDefaultTimeout(12000)
 const errors=[];page.on('pageerror',e=>errors.push(String(e)))
 await page.goto('http://localhost:5173/#studio',{waitUntil:'domcontentloaded'})
 await page.evaluate(()=>{const st=window.__omniframe_store;st.setState({assets:[],clips:[],tracks:[],selectedClipId:null,selectedClipIds:[],rightOpen:true,sidebarSectionMode:'tabs'});const c=document.createElement('canvas');c.width=320;c.height=180;st.getState().addAsset({id:'plate',kind:'image',name:'Plate',url:c.toDataURL(),duration:5,width:320,height:180,size:100});const t=st.getState().ensureTrack('video');st.getState().addClipToTrack(t,'plate',0);st.getState().selectClip(st.getState().clips[0].id)})
 await page.getByTestId('section-tab-effect-mask').click()
 await page.getByLabel('New mask shape').selectOption('star')
 await page.getByTestId('add-effect-mask-btn').click()
 await page.getByTestId('add-effect-mask-hexagon').click()
 await page.getByTestId('add-effect-mask-text').click()
 await page.getByLabel('Effect mask font',{exact:true}).selectOption('cursive')
 await page.getByTestId('add-effect-mask-custom').click()
 await page.getByLabel('Point 1 X').fill('42')
 await page.getByLabel('Effect mask curve').focus();await page.keyboard.press('End')
 await page.getByTestId('effect-mask-draw-preview').click()
 const overlay=page.getByTestId('effect-mask-draw-overlay');await overlay.waitFor()
 const box=await overlay.boundingBox()
 for(const [x,y] of [[.26,.3],[.7,.3],[.5,.7]])await page.mouse.click(box.x+box.width*x,box.y+box.height*y)
 let drawn=await page.evaluate(()=>window.__omniframe_store.getState().clips[0].adjustmentMask.regions.at(-1).points)
 assert.equal(drawn.length,3);assert.equal(drawn[0].x,.25)
 assert.equal(await page.evaluate(()=>window.__omniframe_store.getState().clips[0].adjustmentMask.regions.at(-1).curve),1)
 const handle=await overlay.locator('[data-handle="outHandle"]').boundingBox()
 await page.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);await page.mouse.down();await page.mouse.move(handle.x+handle.width/2+18,handle.y+handle.height/2+12,{steps:4});await page.mouse.up()
 assert(await page.evaluate(()=>!!window.__omniframe_store.getState().clips[0].adjustmentMask.regions.at(-1).points[0].outHandle))
 await page.getByTestId('effect-mask-reset-handles').click()
 assert.equal(await page.evaluate(()=>window.__omniframe_store.getState().clips[0].adjustmentMask.regions.at(-1).points[0].outHandle),undefined)
 await page.evaluate(()=>window.__omniframe_store.getState().undo())
 assert(await page.evaluate(()=>!!window.__omniframe_store.getState().clips[0].adjustmentMask.regions.at(-1).points[0].outHandle))
 await page.evaluate(()=>window.__omniframe_store.getState().redo())
 await page.mouse.move(box.x+box.width*.25,box.y+box.height*.3)
 await page.mouse.down();await page.mouse.move(box.x+box.width*.35,box.y+box.height*.35,{steps:5});await page.mouse.up()
 drawn=await page.evaluate(()=>window.__omniframe_store.getState().clips[0].adjustmentMask.regions.at(-1).points)
 assert(drawn[0].x>.3 && drawn[0].y>.3)
 await page.getByTestId('effect-mask-snap').click()
 await page.mouse.click(box.x+box.width*.26,box.y+box.height*.55)
 drawn=await page.evaluate(()=>window.__omniframe_store.getState().clips[0].adjustmentMask.regions.at(-1).points)
 assert(Math.abs(drawn[3].x-.26)<.005)
 await page.getByTestId('effect-mask-freehand').click()
 await page.mouse.move(box.x+box.width*.2,box.y+box.height*.2);await page.mouse.down()
 for(const [x,y] of [[.8,.2],[.8,.8],[.2,.8],[.2,.2]])await page.mouse.move(box.x+box.width*x,box.y+box.height*y,{steps:8})
 await page.mouse.up()
 drawn=await page.evaluate(()=>window.__omniframe_store.getState().clips[0].adjustmentMask.regions.at(-1).points)
 assert(drawn.length>=8,`freehand samples ${drawn.length}`)
 await page.evaluate(()=>window.__omniframe_store.getState().undo())
 const undone=await page.evaluate(()=>window.__omniframe_store.getState().clips[0].adjustmentMask.regions.at(-1).points.length)
 assert(undone<drawn.length,'one undo reverses the drawn outline')
 await page.evaluate(()=>window.__omniframe_store.getState().redo())
 assert.equal(await page.evaluate(()=>window.__omniframe_store.getState().clips[0].adjustmentMask.regions.at(-1).points.length),drawn.length)
 await page.screenshot({path:'/tmp/omniframe-effect-mask-editor.png',timeout:10000})
 await page.getByTestId('effect-mask-draw-preview').click()
 await page.evaluate(()=>window.__omniframe_store.setState({activeSelection:{type:'rectangle',bounds:{x:.1,y:.2,width:.3,height:.4}}}))
 await page.getByTestId('effect-mask-from-selection').click()
 const r=await page.evaluate(()=>window.__omniframe_store.getState().clips[0].adjustmentMask.regions)
 assert.deepEqual(r.map(x=>x.shape),['star','hexagon','text','custom','rectangle'])
 assert.equal(r[2].fontFamily,'cursive');assert(r[3].points.length>=8);assert.equal(r[4].centerX,.25);assert.equal(r[4].centerY,.4)
 assert.deepEqual(errors,[])
 console.log('PASS live effect-mask drawing, freehand, snapping, curves, selection and undo')
}finally{await browser.close()}
